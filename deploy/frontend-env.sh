#!/bin/sh
set -eu

LIVE_API_BASE_URL="${API_BASE_URL:-${VITE_LIVE_API_BASE_URL:-http://localhost:8000}}"
SUPPORTS_AGENT_TOOLS="${SUPPORTS_AGENT_TOOLS:-${VITE_SUPPORTS_AGENT_TOOLS:-false}}"
SUPPORTS_EDIT_RECORDS="${SUPPORTS_EDIT_RECORDS:-${VITE_SUPPORTS_EDIT_RECORDS:-true}}"
SUPPORTS_EDIT_EXISTING_RESOURCES="${SUPPORTS_EDIT_EXISTING_RESOURCES:-${VITE_SUPPORTS_EDIT_EXISTING_RESOURCES:-${SUPPORTS_EDIT_RECORDS}}}"
SUPPORTS_ASK_PATRA="${SUPPORTS_ASK_PATRA:-${VITE_SUPPORTS_ASK_PATRA:-false}}"
SUPPORTS_MCP_EXPLORER="${SUPPORTS_MCP_EXPLORER:-${VITE_SUPPORTS_MCP_EXPLORER:-false}}"
SUPPORTS_DOMAIN_EXPERIMENTS="${SUPPORTS_DOMAIN_EXPERIMENTS:-${VITE_SUPPORTS_DOMAIN_EXPERIMENTS:-false}}"
SUPPORTS_DEV_OPEN_ACCESS="${SUPPORTS_DEV_OPEN_ACCESS:-${VITE_SUPPORTS_DEV_OPEN_ACCESS:-false}}"
ASSET_ORG="${ASSET_ORG:-${VITE_ASSET_ORG:-}}"
ASSET_API_KEY="${ASSET_API_KEY:-${VITE_ASSET_API_KEY:-}}"
MCP_BASE_URL="${MCP_BASE_URL:-${VITE_MCP_BASE_URL:-http://localhost:8050}}"

cat > /usr/share/nginx/html/env.js <<EOF
window.__PATRA_CONFIG__ = {
  API_BASE_URL: "${LIVE_API_BASE_URL}",
  SUPPORTS_AGENT_TOOLS: "${SUPPORTS_AGENT_TOOLS}",
  SUPPORTS_EDIT_EXISTING_RESOURCES: "${SUPPORTS_EDIT_EXISTING_RESOURCES}",
  SUPPORTS_EDIT_RECORDS: "${SUPPORTS_EDIT_RECORDS}",
  SUPPORTS_ASK_PATRA: "${SUPPORTS_ASK_PATRA}",
  SUPPORTS_MCP_EXPLORER: "${SUPPORTS_MCP_EXPLORER}",
  SUPPORTS_DOMAIN_EXPERIMENTS: "${SUPPORTS_DOMAIN_EXPERIMENTS}",
  SUPPORTS_DEV_OPEN_ACCESS: "${SUPPORTS_DEV_OPEN_ACCESS}",
  ASSET_ORG: "${ASSET_ORG}",
  ASSET_API_KEY: "${ASSET_API_KEY}",
  MCP_BASE_URL: "${MCP_BASE_URL}"
};
EOF

chmod 644 /usr/share/nginx/html/env.js
